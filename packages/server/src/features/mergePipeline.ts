import { stringify } from 'yaml';
import type { PipelineModel } from '@gitlab-ci-preview/shared';
import { REFERENCE_TAG } from '../referenceTag.js';

/**
 * Render the fully-resolved pipeline as a single YAML document: includes fetched,
 * `extends` chains flattened, and top-level `default:` merged into each job.
 *
 * This is a read-only debugging view. `extends:` keys are dropped from each job
 * (their content is already merged in); `!reference` tags are left unexpanded and
 * round-trip through the custom YAML tag.
 */
export function buildMergedPipeline(model: PipelineModel): string {
  const out: Record<string, unknown> = {};
  if (model.stages?.length) out.stages = model.stages;
  if (model.workflow && Object.keys(model.workflow).length) out.workflow = model.workflow;
  if (model.defaults && Object.keys(model.defaults).length) out.default = model.defaults;
  if (model.globalVariables && Object.keys(model.globalVariables).length) out.variables = model.globalVariables;

  for (const job of model.jobs) {
    const spec = { ...job.raw };
    delete spec.extends; // already flattened into the job
    out[job.name] = spec;
  }

  const header =
    `# Merged pipeline for ${model.rootUri}\n` +
    `# Generated by GitLab CI Preview — includes / extends / default resolved.\n` +
    `# Read-only preview. !reference tags are left unexpanded.\n\n`;
  return header + stringify(out, { customTags: [REFERENCE_TAG] });
}
